    a=json.loads(raw);decoded=lzma.decompress(base64.b64decode(a['data']),memlimit=100000000)
    need(len(decoded)==a['decoded_bytes'] and hashlib.sha256(decoded).hexdigest()==a['decoded_sha256'],'archive identity')
    report={'verdict':'candidate_only','trusted_verifier_receipt':False,'complete':False,'source_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),'input_sha256':hashlib.sha256(raw).hexdigest(),'runtime':platform.python_version()}
    try:report['results']=analyze(json.loads(decoded));report['complete']=True;code=0
    except (ValueError,KeyError,TypeError,StopIteration) as ex:report['error']=str(ex);code=1
    report['elapsed_seconds']=round(time.monotonic()-start,6);out=json.dumps(report,sort_keys=True,separators=(',',':'))+'\n';need(len(out)<65536,'output cap');print(out,end='');return code
